const BLANK = Array(7).fill('00000')

// cell：像素格大小；step：格距；dots：是否画出灭掉的暗点
export default function PixelMonogram({ text, cell: CELL = 14, step: STEP = 18, dots = true, className = '' }) {
  const glyphs = text.split('').map((ch) => FONT[ch] || BLANK)
  const cols = glyphs.length * 6 - 1 // 每个字 5 列 + 1 列间隔
  const lit = (r, c) => {
    const g = glyphs[Math.floor(c / 6)]
    const x = c % 6
    return x < 5 && g[r][x] === '1'
  }
  const cells = []
  for (let r = 0; r < 7; r++)
    for (let c = 0; c < cols; c++) {
      const on = lit(r, c)
      cells.push(
        on ? (
          <rect key={`${r}-${c}`} className="px px--on" x={c * STEP} y={r * STEP} width={CELL} height={CELL} rx={CELL / 7} style={{ '--c': c, '--r': r }} />
        ) : (
          dots && <circle key={`${r}-${c}`} className="px" cx={c * STEP + CELL / 2} cy={r * STEP + CELL / 2} r="1.6" />
        )
      )
    }
  return (
    <svg className={`pixel-mono ${className}`} width={cols * STEP - (STEP - CELL)} height={7 * STEP - (STEP - CELL)} viewBox={`0 0 ${cols * STEP - (STEP - CELL)} ${7 * STEP - (STEP - CELL)}`} role="img" aria-label={text}>
      {cells}
    </svg>
  )
}
